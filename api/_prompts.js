/** 준비 질문 답변을 시스템 프롬프트 뒤에 붙인다 */
function withUserContext(system, { nickname, prevType, reason }) {
  const lines = [];
  if (nickname) lines.push(`사용자가 불리고 싶어 하는 이름: ${nickname}`);
  if (prevType) lines.push(`사용자가 알고 있던 기존 검사 결과: ${prevType} (참고만 하고, 이 유형에 맞춰 해석하지 마)`);
  if (reason) lines.push(`사용자가 이 해석을 해보려는 이유: ${reason}`);
  if (!lines.length) return system;
  return `${system}\n\n# 사용자 정보\n${lines.join('\n')}`;
}

